#!/usr/bin/env node
// Offline validator for avatar-frame PNGs. Node only, no dependencies.
// Inputs and hashes live in each event's frames/manifest.json; see events/README.md.
// The PNGs are published as they are; this writes only their registry, events/frames.js.
//   node tools/build-event-frames.mjs            validate inputs and write the registry
//   node tools/build-event-frames.mjs --check    validate and fail if the registry is stale
//   node tools/build-event-frames.mjs --measure <file.png>   suggest a manifest photo window
import { readFile, writeFile, lstat, realpath } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { inflateSync, crc32 } from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join, basename, resolve } from 'node:path';

const root = resolve(fileURLToPath(new URL('../', import.meta.url)));
// Explicit, in public catalog order. Event folders are never discovered by walking.
const EVENT_DIRECTORIES = ['wordcamp-asia', 'wordcamp-europe', 'wordcamp-us', 'wordcamp-india'];
// The avatar layout is a native 1080 px square; supplied frames are scaled to it.
const OUTPUT_SIZE = 1080;
const MIN_SIZE = 1080, MAX_SIZE = 2048;
const MAX_FRAME_BYTES = 1024 * 1024;
const MAX_ROLES = 10;
// Output pixels by which the photo extends past the declared window, under opaque
// artwork. Covers the window's antialiased edge, resampling and the photo's own clip edge.
const PHOTO_MARGIN = 3;
// Source pixels: antialiasing allowed outside the declared window, and the inset
// used when measuring how much of the window is open.
const EDGE_TOLERANCE = 1.5;
const WINDOW_INSET = 2;
const HEADER = '// Generated by tools/build-event-frames.mjs from each event\'s frames/manifest.json; do not hand-edit.\n';

const fail = message => { throw new Error(message); };
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const round = value => Math.round(value * 100) / 100;
const plain = value => value && typeof value === 'object' && !Array.isArray(value);
const exactKeys = (value, required, optional, label) => {
  if (!plain(value)) fail(`${label} must be an object.`);
  const keys = Object.keys(value);
  for (const key of required) if (!keys.includes(key)) fail(`${label} is missing "${key}".`);
  for (const key of keys) if (!required.includes(key) && !optional.includes(key)) fail(`${label} has an unsupported key "${key}".`);
};
const text = (value, label, max = 600) => {
  if (typeof value !== 'string' || !value.trim() || value.length > max || /[\u0000-\u001f\u007f]/.test(value)) fail(`${label} must be 1-${max} printable characters.`);
  return value;
};

// Minimal strict decoder: 8-bit RGBA, non-interlaced, single image. Returns alpha only.
function decodePng(bytes, label = 'PNG') {
  const signature = [137, 80, 78, 71, 13, 10, 26, 10];
  if (bytes.length < 57 || signature.some((value, index) => bytes[index] !== value)) fail(`${label}: not a PNG file.`);
  let offset = 8, header = null, ended = false; const data = [];
  while (offset < bytes.length) {
    if (ended) fail(`${label}: data after the final PNG chunk.`);
    if (offset + 12 > bytes.length) fail(`${label}: truncated PNG chunk.`);
    const length = bytes.readUInt32BE(offset); const type = bytes.toString('latin1', offset + 4, offset + 8);
    const end = offset + 12 + length;
    if (end > bytes.length) fail(`${label}: truncated ${type} chunk.`);
    if (crc32(bytes.subarray(offset + 4, offset + 8 + length)) !== bytes.readUInt32BE(offset + 8 + length)) fail(`${label}: corrupt ${type} chunk.`);
    const body = bytes.subarray(offset + 8, offset + 8 + length);
    if (!header && type !== 'IHDR') fail(`${label}: missing PNG header.`);
    if (type === 'IHDR') {
      if (header || length !== 13) fail(`${label}: invalid PNG header.`);
      header = { width: body.readUInt32BE(0), height: body.readUInt32BE(4), depth: body[8], color: body[9], compression: body[10], filter: body[11], interlace: body[12] };
    } else if (type === 'IDAT') data.push(body);
    else if (type === 'acTL' || type === 'fcTL' || type === 'fdAT') fail(`${label}: animated PNGs are not supported.`);
    else if (type === 'IEND') ended = true;
    offset = end;
  }
  if (!header || !ended || !data.length) fail(`${label}: incomplete PNG.`);
  const { width, height } = header;
  if (header.depth !== 8 || header.color !== 6) fail(`${label}: export as 8-bit RGBA (truecolor with alpha), not palette, grayscale or 16-bit.`);
  if (header.interlace !== 0 || header.compression !== 0 || header.filter !== 0) fail(`${label}: export without interlacing.`);
  if (width !== height || width < MIN_SIZE || width > MAX_SIZE) fail(`${label}: must be square, ${MIN_SIZE}-${MAX_SIZE} px per side (found ${width}x${height}).`);
  const stride = width * 4;
  const raw = inflateSync(Buffer.concat(data), { maxOutputLength: (stride + 1) * height });
  if (raw.length !== (stride + 1) * height) fail(`${label}: unexpected pixel data length.`);
  const alpha = new Uint8Array(width * height);
  let previous = new Uint8Array(stride), current = new Uint8Array(stride);
  for (let y = 0; y < height; y++) {
    const start = y * (stride + 1); const filter = raw[start];
    if (filter > 4) fail(`${label}: unsupported PNG filter.`);
    for (let i = 0; i < stride; i++) {
      const left = i >= 4 ? current[i - 4] : 0, up = previous[i], corner = i >= 4 ? previous[i - 4] : 0;
      let predictor = 0;
      if (filter === 1) predictor = left;
      else if (filter === 2) predictor = up;
      else if (filter === 3) predictor = (left + up) >> 1;
      else if (filter === 4) {
        const estimate = left + up - corner;
        const a = Math.abs(estimate - left), b = Math.abs(estimate - up), c = Math.abs(estimate - corner);
        predictor = a <= b && a <= c ? left : b <= c ? up : corner;
      }
      current[i] = (raw[start + 1 + i] + predictor) & 255;
    }
    for (let x = 0; x < width; x++) alpha[y * width + x] = current[x * 4 + 3];
    [previous, current] = [current, previous];
  }
  return { width, height, alpha };
}

// The photo shows through one circular window. Everything outside it must be opaque,
// or the exported image would have holes that no photo covers.
function checkWindow({ width, height, alpha }, window, label) {
  const { cx, cy, r } = window;
  let outside = 0, clear = 0, disc = 0, minX = width, minY = height, maxX = -1, maxY = -1, strayMinX = width, strayMinY = height, strayMaxX = -1, strayMaxY = -1;
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const value = alpha[y * width + x];
    const distance = Math.hypot(x + 0.5 - cx, y + 0.5 - cy);
    if (distance < r - WINDOW_INSET) { disc++; if (value === 0) clear++; }
    if (value === 255) continue;
    if (distance > r + EDGE_TOLERANCE) {
      outside++;
      strayMinX = Math.min(strayMinX, x); strayMaxX = Math.max(strayMaxX, x); strayMinY = Math.min(strayMinY, y); strayMaxY = Math.max(strayMaxY, y);
    } else { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
  }
  if (outside) fail(`${label}: ${outside} pixels outside the photo window are not fully opaque (x ${strayMinX}-${strayMaxX}, y ${strayMinY}-${strayMaxY}). Re-export with artwork covering the whole canvas, or correct the manifest window.`);
  if (alpha[Math.floor(cy) * width + Math.floor(cx)] !== 0) fail(`${label}: the center of the photo window is not transparent.`);
  if (clear / disc < 0.4) fail(`${label}: less than 40% of the declared photo window is transparent. Check the manifest window.`);
  // A window declared larger than the real opening would shrink and misplace the photo.
  const touching = [minX - (cx - r), (cx + r) - (maxX + 1), minY - (cy - r), (cy + r) - (maxY + 1)].filter(gap => Math.abs(gap) <= 2).length;
  if (touching < 3) fail(`${label}: the transparent opening does not match the declared window (found x ${minX}-${maxX}, y ${minY}-${maxY}). Run --measure and update the manifest.`);
}

function measureWindow({ width, height, alpha }) {
  // Longest horizontal mostly-transparent run gives the diameter; decoration may hide
  // other edges. An antialiased edge pixel counts as open from half coverage.
  let best = { length: 0, x: 0, y: 0 };
  for (let y = 0; y < height; y++) {
    let start = -1;
    for (let x = 0; x <= width; x++) {
      const open = x < width && alpha[y * width + x] < 128;
      if (open && start < 0) start = x;
      if (!open && start >= 0) { if (x - start > best.length) best = { length: x - start, x: start, y }; start = -1; }
    }
  }
  if (!best.length) fail('No transparent window found.');
  const r = best.length / 2, cx = best.x + r;
  // The opening's highest point, near the vertical axis, fixes the center height.
  let top = height;
  for (let x = Math.floor(cx - r / 8); x <= Math.ceil(cx + r / 8); x++) {
    for (let y = 0; y < top; y++) if (alpha[y * width + x] < 128) { top = y; break; }
  }
  return { cx: Math.round(cx * 2) / 2, cy: Math.round((top + r) * 2) / 2, r: Math.floor(r) };
}

async function localFile(directory, name, label) {
  if (typeof name !== 'string' || basename(name) !== name || !/^[a-z0-9][a-z0-9-]*\.png$/.test(name)) fail(`${label}: frame paths are lowercase local .png basenames (found ${JSON.stringify(name)}).`);
  const path = join(directory, name);
  let stat;
  try { stat = await lstat(path); } catch { fail(`${label}: missing file ${name}.`); }
  if (!stat.isFile() || await realpath(path) !== path) fail(`${label}: ${name} must be a regular, non-symlinked file.`);
  return readFile(path);
}

async function loadSources() {
  const editions = [];
  for (const event of EVENT_DIRECTORIES) {
    const directory = join(root, 'events', event, 'frames');
    let manifest;
    try { manifest = JSON.parse(await readFile(join(directory, 'manifest.json'), 'utf8')); }
    catch (error) { if (error.code === 'ENOENT') continue; fail(`events/${event}/frames/manifest.json: ${error.message}`); }
    const where = `events/${event}/frames/manifest.json`;
    exactKeys(manifest, ['editions', 'source', 'rights', 'assets'], [], where);
    text(manifest.source, `${where} source`); text(manifest.rights, `${where} rights`);
    if (!plain(manifest.editions) || !Array.isArray(manifest.assets)) fail(`${where}: editions must be an object and assets a list.`);
    const { editions: known } = await import(pathToFileURL(join(root, 'events', event, 'event.js')).href);
    const assets = new Map();
    for (const item of manifest.assets) {
      exactKeys(item, ['path', 'sha256', 'bytes', 'width', 'height', 'sourceName'], ['sourceSha256', 'sourceBytes', 'conversion'], `${where} asset`);
      const label = `events/${event}/frames/${item.path}`;
      if (assets.has(item.path)) fail(`${label}: listed twice.`);
      text(item.sourceName, `${label} sourceName`, 200);
      if (item.conversion !== undefined) text(item.conversion, `${label} conversion`);
      if (item.sourceSha256 !== undefined && !/^[a-f0-9]{64}$/.test(item.sourceSha256)) fail(`${label}: invalid sourceSha256.`);
      if (item.sourceBytes !== undefined && !(Number.isInteger(item.sourceBytes) && item.sourceBytes > 0)) fail(`${label}: invalid sourceBytes.`);
      const bytes = await localFile(directory, item.path, where);
      if (bytes.length !== item.bytes || sha256(bytes) !== item.sha256) fail(`${label}: bytes/hash do not match the manifest (found ${bytes.length} bytes, sha256 ${sha256(bytes)}).`);
      if (bytes.length > MAX_FRAME_BYTES) fail(`${label}: ${bytes.length} bytes exceeds the ${MAX_FRAME_BYTES}-byte frame budget. Losslessly optimize the PNG.`);
      const image = decodePng(bytes, label);
      if (image.width !== item.width || image.height !== item.height) fail(`${label}: dimensions do not match the manifest.`);
      assets.set(item.path, { item, bytes, image, used: false });
    }
    for (const [edition, entry] of Object.entries(manifest.editions)) {
      const label = `${where} edition ${edition}`;
      if (!known.some(item => item.id === edition)) fail(`${label}: not an edition in events/${event}/event.js.`);
      // The published path is /frames/<edition>-<role>.png, served from this event's folder.
      if (!edition.startsWith(`${event.replace('wordcamp-', '')}-`)) fail(`${label}: edition IDs in events/${event} start with "${event.replace('wordcamp-', '')}-".`);
      exactKeys(entry, ['window', 'roles'], [], label);
      exactKeys(entry.window, ['cx', 'cy', 'r'], [], `${label} window`);
      for (const key of ['cx', 'cy', 'r']) if (!Number.isFinite(entry.window[key]) || entry.window[key] <= 0) fail(`${label}: window.${key} must be a positive number of source pixels.`);
      if (!plain(entry.roles) || !Object.keys(entry.roles).length || Object.keys(entry.roles).length > MAX_ROLES) fail(`${label}: roles must map 1-${MAX_ROLES} role IDs to frame files.`);
      const roles = [];
      let size = 0;
      for (const [role, path] of Object.entries(entry.roles)) {
        if (!/^[a-z]{1,24}$/.test(role)) fail(`${label}: invalid role ID ${JSON.stringify(role)}.`);
        if (path !== `${edition}-${role}.png`) fail(`${label}: the ${role} frame must be named ${edition}-${role}.png (found ${JSON.stringify(path)}).`);
        const asset = assets.get(path);
        if (!asset) fail(`${label}: role ${role} refers to an unlisted asset ${JSON.stringify(path)}.`);
        if (size && asset.image.width !== size) fail(`${label}: every role's frame must share one size.`);
        size = asset.image.width;
        const { cx, cy, r } = entry.window;
        if (cx - r < 0 || cy - r < 0 || cx + r > size || cy + r > size) fail(`${label}: the window must lie inside the ${size} px canvas.`);
        checkWindow(asset.image, entry.window, `events/${event}/frames/${path}`);
        asset.used = true;
        roles.push({ role, path, asset });
      }
      const scale = OUTPUT_SIZE / size;
      const cx = round(entry.window.cx * scale), cy = round(entry.window.cy * scale), r = round(entry.window.r * scale + PHOTO_MARGIN);
      editions.push({ edition, event, photo: { cx, cy, r, x: round(cx - r), y: round(cy - r), size: round(r * 2) }, roles });
    }
    for (const [path, asset] of assets) if (!asset.used) fail(`events/${event}/frames/${path}: listed in assets but not assigned to an edition role.`);
  }
  if (new Set(editions.map(item => item.edition)).size !== editions.length) fail('An edition has supplied frames in more than one event folder.');
  return editions;
}

function outputs(editions) {
  // Metadata only: the public catalog and the renderer import this module. The PNGs
  // themselves are published as plain files and fetched by events/frame-loader.js.
  let registry = HEADER + '// Metadata only: the artwork is published as /frames/<edition>-<role>.png and fetched by events/frame-loader.js.\n'
    + '// `photo` is in 1080-unit output space; `length` is the exact length of the PNG as an embedded data URL.\n'
    + 'export const EVENT_FRAMES = Object.freeze({\n';
  for (const { edition, photo, roles } of editions) {
    registry += `  '${edition}': Object.freeze({\n    photo: Object.freeze({ ${Object.entries(photo).map(([key, value]) => `${key}: ${value}`).join(', ')} }),\n    roles: Object.freeze({\n`;
    for (const { role, asset } of roles) {
      registry += `      ${role}: Object.freeze({ sha256: '${sha256(asset.bytes)}', bytes: ${asset.bytes.length}, width: ${asset.image.width}, height: ${asset.image.height}, length: ${'data:image/png;base64,'.length + Math.ceil(asset.bytes.length / 3) * 4} }),\n`;
    }
    registry += '    })\n  }),\n';
  }
  registry += '});\n';
  return new Map([['frames.js', registry]]);
}

const [mode, target, ...extra] = process.argv.slice(2);
if (mode === '--measure') {
  if (!target || extra.length) fail('Usage: node tools/build-event-frames.mjs --measure <file.png>');
  const image = decodePng(await readFile(target), basename(target));
  console.log(JSON.stringify({ file: basename(target), width: image.width, height: image.height, window: measureWindow(image) }));
} else {
  if ((mode && mode !== '--check') || target) fail('Usage: node tools/build-event-frames.mjs [--check | --measure <file.png>]');
  const editions = await loadSources();
  const files = outputs(editions);
  const stale = [];
  for (const [path, content] of files) {
    let current = null;
    try { current = await readFile(join(root, 'events', path), 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current !== content) stale.push(`events/${path}`);
  }
  if (mode === '--check') {
    if (stale.length) fail(`The generated frame registry is out of date; run node tools/build-event-frames.mjs: ${stale.join(', ')}`);
  } else {
    for (const [path, content] of files) await writeFile(join(root, 'events', path), content);
  }
  const frames = editions.flatMap(item => item.roles);
  console.log(JSON.stringify({
    mode: mode === '--check' ? 'check' : 'write', editions: editions.map(item => item.edition), frames: frames.length,
    sourceBytes: frames.reduce((sum, item) => sum + item.asset.bytes.length, 0), written: mode === '--check' ? [] : stale,
  }));
}
